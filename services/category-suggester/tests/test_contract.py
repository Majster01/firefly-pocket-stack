import json
import unittest

from suggester import cli, contract
from suggester.contract import Suggestion
from tests.helpers import txn


def firefly_escape(text: str) -> str:
    """How Firefly 6.6.6 returns rule descriptions (PHP htmlspecialchars, ENT_QUOTES)."""
    return text.replace("&", "&amp;").replace('"', "&quot;").replace("'", "&#039;").replace("<", "&lt;").replace(">", "&gt;")


def sample() -> Suggestion:
    return Suggestion(
        category="Food & Drink",
        confidence=0.861,
        low_confidence=False,
        company="Burgerlab — burger restaurant, Ljubljana",
        reason="Card purchase at a burger chain's 'Center' branch <test>",
        transactions=[txn("BURGERLAB LJ-CENTER", journal_id=285), txn("BURGERLAB LJ-CENTER", journal_id=242)],
        triggers=[("description_contains", "BURGERLAB")],
        model="claude-haiku-5-5",
    )


class Metadata(unittest.TestCase):
    def test_round_trip_plain(self):
        meta = sample().metadata("2026-10-29")
        self.assertEqual(contract.decode_description(contract.encode_description(meta)), meta)

    def test_round_trip_through_firefly_html_escaping(self):
        meta = sample().metadata("2026-10-29")
        escaped = firefly_escape(contract.encode_description(meta))
        self.assertIn("&quot;", escaped)
        self.assertIn("&amp;", escaped)
        self.assertIn("&#039;", escaped)
        self.assertEqual(contract.decode_description(escaped), meta)

    def test_hand_written_sample_rule_from_firefly(self):
        # Verbatim shape of rule 18 as Firefly returned it.
        description = (
            "firefly-pocket-suggestion:v1 {&quot;v&quot;: 1, &quot;transactions&quot;: [{&quot;transaction_id&quot;: 301, "
            "&quot;journal_id&quot;: 301}], &quot;reason&quot;: &quot;Payment to a private person; &#039;kosilo&#039; "
            "means lunch&quot;, &quot;category&quot;: &quot;Food &amp; Drink&quot;}"
        )
        meta = contract.decode_description(description)
        self.assertEqual(meta["category"], "Food & Drink")
        self.assertEqual(contract.journal_ids(meta), {301})
        self.assertIn("'kosilo'", meta["reason"])

    def test_unknown_major_version_and_foreign_rules_are_ignored(self):
        self.assertIsNone(contract.decode_description('firefly-pocket-suggestion:v1 {"v": 2, "transactions": []}'))
        self.assertIsNotNone(contract.decode_description('firefly-pocket-suggestion:v1 {"v": "1.3", "transactions": []}'))
        self.assertIsNone(contract.decode_description("Auto-generated by scripts/seed-category-rules.py"))
        self.assertIsNone(contract.decode_description("firefly-pocket-suggestion:v1 not json"))
        self.assertIsNone(contract.decode_description(None))

    def test_metadata_fields(self):
        meta = sample().metadata("2026-10-29")
        self.assertEqual(
            set(meta),
            {"v", "transactions", "category", "confidence", "low_confidence", "basis", "company", "reason", "model", "created"},
        )
        self.assertEqual(meta["transactions"], [{"transaction_id": 285, "journal_id": 285}, {"transaction_id": 242, "journal_id": 242}])
        self.assertEqual(meta["confidence"], 0.86)
        self.assertEqual(meta["basis"], "description")


class RulePayload(unittest.TestCase):
    def test_payload_follows_the_contract(self):
        payload = sample().rule_payload("4", "2026-10-29")
        self.assertEqual(payload["title"], "Suggest: Food & Drink · Burgerlab")
        self.assertEqual(payload["rule_group_id"], "4")
        self.assertIs(payload["active"], False)
        self.assertEqual(payload["trigger"], "store-journal")
        self.assertIs(payload["strict"], False)
        self.assertIs(payload["stop_processing"], True)
        self.assertEqual(
            payload["triggers"], [{"type": "description_contains", "value": "BURGERLAB", "active": True, "stop_processing": True}]
        )
        self.assertEqual(
            payload["actions"], [{"type": "set_category", "value": "Food & Drink", "active": True, "stop_processing": False}]
        )
        self.assertTrue(payload["description"].startswith("firefly-pocket-suggestion:v1 {"))
        json.loads(payload["description"][len("firefly-pocket-suggestion:v1 ") :])  # plain JSON on the way in

    def test_title_falls_back_to_the_keyword(self):
        s = sample()
        s.company = None
        self.assertEqual(s.title, "Suggest: Food & Drink · BURGERLAB")


class Reminder(unittest.TestCase):
    def test_reminder_text(self):
        self.assertIsNone(cli.reminder([]))
        self.assertEqual(cli.reminder([{"low_confidence": False}]), "1 category suggestion waiting for review.")
        self.assertEqual(
            cli.reminder([{"low_confidence": True}, {"low_confidence": False}, {}]),
            "3 category suggestions waiting for review (1 low-confidence).",
        )


